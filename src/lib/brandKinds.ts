const norm = (s: string) =>
  s
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9&]+/g, " ")
    .trim();

const TABLE = BRAND_KINDS.map(([b, k]) => [norm(b), k] as const).sort(
  (a, b) => b[0].length - a[0].length,
);

/** The kind of thing a search that starts with a known brand is after: "western star" → "butter". */
export function brandKind(search: string): string | undefined {
  const q = ` ${norm(search)} `;
  return TABLE.find(([b]) => q.startsWith(` ${b} `))?.[1];
}
