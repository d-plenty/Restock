// 0.9.11: price helper phone mode. A spare Android phone, left on its charger, searches Coles and
// Woolworths for common items through the week (the first page of results for each, no paging) and
// sends what it found, product facts and shelf prices only, to the restock-prices collector on your
// own network (its "helper" address and key). The collector folds them into restock-prices, Restock's
// shared price history, at its next weekly run, so every phone's "Judge deals from day one" gets
// them. The searching itself is done by PriceHelper.java in the background, while charging on Wi-Fi.

export const HELPER_CHAINS = ['coles', 'woolworths'] as const;

/** About one search (both shops) every 10 minutes while charging: three every half hour or so. */
export const HELPER_PER_RUN = 3;

export interface PriceHelperSettings {
  enabled: boolean;
  /** The collector's helper address, e.g. http://192.168.1.20:8790 */
  url?: string;
  /** The collector's HELPER_KEY. Stays on this phone (never shared with the household). */
  key?: string;
  /** What to search, one per line. Unset: the built-in list. */
  searches?: string[];
}

export const DEFAULT_PRICE_HELPER: PriceHelperSettings = { enabled: false };

/** The searches it runs: its own list when there is one, else the built-in one. */
export const helperSearches = (s?: PriceHelperSettings): string[] => (s?.searches?.length ? s.searches : HELPER_SEARCHES);

/** One search per line, tidied: trimmed, lower case, each once, at most 1000, each at most 60 characters. */
export function tidySearches(text: string): string[] {
  const out: string[] = [];
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim().replace(/\s+/g, ' ').toLowerCase().slice(0, 60);
    if (t && !out.includes(t)) out.push(t);
    if (out.length >= 1000) break;
  }
  return out;
}

/** "http://192.168.1.20:8790" with nothing after it, or undefined when it isn't an http(s) address. */
export function tidyHelperUrl(v: string): string | undefined {
  const t = v.trim().replace(/\/+$/, '');
  if (!/^https?:\/\/[^\s/]+(:\d+)?$/i.test(t)) return undefined;
  return t;
}

/** What the phone did this week (kept by PriceHelper.java in the "priceHelper" store). */
export interface PriceHelperState {
  week?: string;
  done?: number;
  of?: number;
  sent?: number;
  waiting?: number;
  lastAt?: string;
  lastError?: string;
  paused?: Record<string, string>;
  /** 0.9.12: set while a run is going. */
  runningSince?: string;
}

/**
 * 0.9.12: the status lines under the buttons. `asked`: when "Run a few now" was tapped (the run can
 * take a few seconds to start). A run "going" for over 15 minutes stopped without saying (the phone
 * was restarted, say), so it isn't shown as going.
 */
export function helperStatus(o: { state?: PriceHelperState; enabled: boolean; of: number; asked?: number; now: number }): string[] {
  const s = o.state;
  const running = !!s?.runningSince && o.now - Date.parse(s.runningSince) < 15 * 60_000;
  const lines: string[] = [];
  if (running) lines.push(`Running now: search ${Math.min((s?.done ?? 0) + 1, s?.of ?? o.of)} of ${s?.of ?? o.of}. Each one takes about a minute.`);
  else if (o.asked && o.now - o.asked < 60_000 && (!s?.lastAt || Date.parse(s.lastAt) < o.asked)) lines.push('Starting…');
  if (s?.week) {
    const parts = [`This week: ${Math.min(s.done ?? 0, s.of ?? o.of)} of ${s.of ?? o.of} searches done`, `${(s.sent ?? 0).toLocaleString()} prices sent`];
    if (s.waiting) parts.push(`${s.waiting.toLocaleString()} waiting to send`);
    if (s.lastAt) parts.push(`last ran ${new Date(s.lastAt).toLocaleString()}`);
    lines.push(parts.join(' · '));
    if (s.paused) for (const [shop, until] of Object.entries(s.paused)) if (Date.parse(until) > o.now) lines.push(`${shop === 'coles' ? 'Coles' : 'Woolworths'} turned it away, so it's resting until ${new Date(until).toLocaleTimeString()}.`);
    if (s.lastError && !running) lines.push(`Last problem: ${s.lastError}`);
  } else if (!running && !lines.length) {
    lines.push(
      o.enabled
        ? 'Not run yet. It runs by itself about every half hour while this phone is charging on Wi-Fi (Android picks the moment), or tap Run a few now.'
        : 'Off.',
    );
  }
  return lines;
}

