const SIZE = /\b\d+(\.\d+)?\s*(x\s*\d+(\.\d+)?\s*)?(kg|g|ml|l|litres?|pk|pack|ea|each|sheets?|rolls?|tabs?|tablets?|capsules?|pods?|bags?)\b/gi;

/** True when a product's name already says its size ("Topz Crackers 227g" and "227 g"). */
export function nameHasSize(name: string, size?: string): boolean {
  if (!size) return true;
  const squash = (s: string) =>
    s
      .toLowerCase()
      .replace(/\s+/g, '')
      .replace(/litres?|ltr/g, 'l');
  return squash(name).includes(squash(size));
}

function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1);
}

/** "Coles Simply Pure Honey Squeeze 400g" → "Honey". Falls back to the name without its size. */
export function genericName(productName: string | undefined, brand?: string): string {
  if (!productName) return '';
  let lower = ` ${productName.toLowerCase().replace(/[’']/g, "'").replace(/\s+/g, ' ')} `;
  // "Spaghetti in Tomato Sauce", "Tuna in Springwater": the thing comes before "in"/"with".
  const head = lower.split(/ (?:in|with) /)[0];
  if (head !== lower && KINDS.some((k) => new RegExp(`\\b${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`).test(head))) lower = `${head} `;
  // "… in Juice / Syrup / Brine / Springwater / Oil": what it's packed in is never the thing itself.
  else if (head !== lower && / (?:in|with) (?:natural |its own |light |heavy )?(?:juice|syrup|brine|spring ?water|water|oil|olive oil)\b/.test(lower))
    lower = `${head} `;
  for (const b of BRAND_ITEMS) if (lower.includes(` ${b} `) || lower.includes(` ${b}'`)) return cap(b);
  // The kind named last is usually the thing itself ("chocolate ice cream topping" → topping, not chocolate).
  let found: { kind: string; at: number } | undefined;
  for (const k of KINDS) {
    const plain = new RegExp(`\\b${k.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`);
    const m = plain.exec(lower);
    if (!m) continue;
    const end = m.index + k.length;
    if (!found || end > found.at + found.kind.length || (end === found.at + found.kind.length && k.length > found.kind.length)) {
      found = { kind: k, at: m.index };
    }
  }
  if (found) return cap(found.kind);
  let rest = productName.replace(SIZE, ' ');
  if (brand) rest = rest.replace(new RegExp(`^\\s*${brand.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'i'), ' ');
  rest = rest.replace(/\s+/g, ' ').trim();
  return cap(rest || productName.trim());
}
