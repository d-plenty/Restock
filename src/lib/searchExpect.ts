/** Is this product the right answer for the word? Undefined when the word has no label yet. */
export function isRight(word: string, name: string): boolean | undefined {
  const x = EXPECT[word];
  if (!x) return undefined;
  return x.want.test(name) && !x.not?.test(name);
}
